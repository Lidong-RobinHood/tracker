#!/usr/bin/env node
// Write precache-list.js: every file the app can request at runtime, with a content hash each.
// sw.js loads the list with importScripts() and stores all of it at install, so the app opens and
// works offline after the first visit (lazily loaded CSS, modules, data and the barcode wasm included).
//
// Usage (repo root):  node tools/build-precache.mjs
// Run it as the last step before a release (docs/RELEASE.md). tests/precache.test.js fails when the
// committed list does not match the files on disk.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const LIST_FILE = 'precache-list.js';

/** Files at the top level that the app loads. sw.js and the list itself are the worker's own scripts. */
const TOP = ['index.html', 'app.css', 'manifest.webmanifest'];
/** Folders whose files the app may load, with the extensions that count as runtime files. */
const DIRS = [
  { dir: 'icons', ext: ['.png'] },
  { dir: 'src', ext: ['.js', '.css', '.json'] },
  { dir: 'vendor', ext: ['.js', '.wasm'] },
];

function walk(root, rel) {
  const out = [];
  for (const name of readdirSync(join(root, rel)).sort()) {
    if (name.startsWith('.')) continue;
    const p = `${rel}/${name}`;
    if (statSync(join(root, p)).isDirectory()) out.push(...walk(root, p));
    else out.push(p);
  }
  return out;
}

/** Short content hash used both by the list and by sw.js (SHA-256, first 16 hex digits). */
export function hashBytes(buf) {
  return createHash('sha256').update(buf).digest('hex').slice(0, 16);
}

/**
 * @param {string} [root]
 * @returns {{hash: string, files: [string, string, number][]}} path (relative to the app root),
 *   content hash, size in bytes; sorted by path. `hash` changes whenever any file changes.
 */
export function collectPrecache(root = ROOT) {
  const paths = [...TOP];
  for (const { dir, ext } of DIRS) paths.push(...walk(root, dir).filter((p) => ext.some((e) => p.endsWith(e))));
  paths.sort();
  const files = paths.map((p) => {
    const buf = readFileSync(join(root, p));
    return [p, hashBytes(buf), buf.length];
  });
  const hash = hashBytes(JSON.stringify(files.map(([p, h]) => [p, h])));
  return { hash, files };
}

/** Source text of precache-list.js (a classic script for importScripts). */
export function renderList({ hash, files }) {
  const total = files.reduce((n, f) => n + f[2], 0);
  return [
    '// Generated by tools/build-precache.mjs. Do not edit; run `node tools/build-precache.mjs` instead.',
    `// ${files.length} files, ${total} bytes. Loaded by sw.js with importScripts() and stored at install.`,
    'self.PRECACHE = {',
    `  hash: '${hash}',`,
    '  files: [',
    ...files.map(([p, h, n]) => `    ['${p}', '${h}', ${n}],`),
    '  ],',
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const data = collectPrecache();
  writeFileSync(join(ROOT, LIST_FILE), renderList(data));
  const total = data.files.reduce((n, f) => n + f[2], 0);
  console.log(`${LIST_FILE}: ${data.files.length} files, ${(total / 1024).toFixed(0)} KiB, hash ${data.hash}`);
}
